export const GLYPHS = {};
for (const [ch, src] of Object.entries(RAW)) {
  const rows = src.split('/');
  const w = rows[0].length;
  while (rows.length < GLYPH_H) rows.push('.'.repeat(w));
  GLYPHS[ch] = { w, rows };
}

export const KNOWN_TAGS = ['c:', '/c', 'shake', '/shake', 'wave', '/wave', 'p:', 'hero'];

export function hasGlyph(ch) {
  return ch === ' ' || ch === '\n' || Object.hasOwn(GLYPHS, ch);
}

export function advance(ch) {
  if (ch === ' ') return SPACE;
  return (GLYPHS[ch]?.w ?? 3) + 1;
}

// Width in pixels of text drawn with the small font. Tags are ignored.
export function textWidth(str) {
  let w = 0;
  let longest = 0;
  for (const t of parseRich(str)) {
    if (t.ch === '\n') {
      longest = Math.max(longest, w - 1);
      w = 0;
      continue;
    }
    w += advance(t.ch);
  }
  return Math.max(longest, w - 1, 0);
}

// Text with tags → one token per character: { ch, color, fx, pause }.
// Tags: {c:gold}…{/c} colour · {shake}…{/shake} · {wave}…{/wave} · {p:0.4} pause · {hero}
export function parseRich(text, opts = {}) {
  const out = [];
  const colors = [];
  let fx = null;
  let pause = 0;
  const push = (ch) => {
    out.push({ ch, color: colors.length ? colors[colors.length - 1] : null, fx, pause });
    pause = 0;
  };
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch === '{') {
      const end = text.indexOf('}', i);
      if (end > i) {
        const tag = text.slice(i + 1, end);
        i = end;
        if (tag.startsWith('c:')) colors.push(tag.slice(2));
        else if (tag === '/c') colors.pop();
        else if (tag === 'shake' || tag === 'wave') fx = tag;
        else if (tag === '/shake' || tag === '/wave') fx = null;
        else if (tag.startsWith('p:')) pause += Number(tag.slice(2)) || 0;
        else if (tag === 'hero') for (const h of opts.hero ?? 'Pip') push(h);
        continue;
      }
    }
    push(ch);
  }
  return out;
}

// Lays text out in lines no wider than maxWidth and groups them into pages.
// Returns pages → lines → { w, glyphs: [{ ch, x, color, fx, pause }] }.
export function layout(text, maxWidth, opts = {}) {
  const maxLines = opts.maxLines ?? 3;
  const tokens = parseRich(text, opts);
  const lines = [];
  let line = [];
  let cursor = 0;
  let word = [];
  let carry = 0;

  const endLine = () => {
    lines.push({ w: Math.max(0, cursor - 1), glyphs: line });
    line = [];
    cursor = 0;
  };

  const placeWord = () => {
    if (!word.length) return;
    let width = -1;
    for (const g of word) width += advance(g.ch);
    let start = line.length ? cursor + SPACE : 0;
    if (line.length && start + width > maxWidth) {
      endLine();
      start = 0;
    }
    cursor = start;
    for (const g of word) {
      const a = advance(g.ch);
      if (line.length && cursor + a - 1 > maxWidth) endLine();
      line.push({ ...g, x: cursor });
      cursor += a;
    }
    word = [];
  };

  for (const t of tokens) {
    if (t.ch === ' ') {
      placeWord();
      carry += t.pause;
      continue;
    }
    if (t.ch === '\n') {
      placeWord();
      carry += t.pause;
      endLine();
      continue;
    }
    word.push(carry ? { ...t, pause: t.pause + carry } : t);
    carry = 0;
  }
  placeWord();
  if (line.length || !lines.length) endLine();

  const pages = [];
  for (let i = 0; i < lines.length; i += maxLines) pages.push(lines.slice(i, i + maxLines));
  return pages;
}
